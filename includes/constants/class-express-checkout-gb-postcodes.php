	/**
	 * Ensures the provided string always contains the last 3 characters for the "inward code".
	 *
	 * @param string $postcode The postcode to be padded.
	 *
	 * @return string The padded postcode.
	 */
	public static function get_padded_postcode( $postcode ) {
		// this method could be implemented as a `for` loop from `4` to `2` to iterate over the constants,
		// but I thought it would be less explicit/harder to read.
		if ( strlen( $postcode ) >= 4 && isset( self::FOUR_LETTER_OUTWARD_CODES[ substr( $postcode, 0, 4 ) ] ) ) {
			return str_pad( $postcode, 7, '0' );
		}

		if ( strlen( $postcode ) >= 3 && isset( self::THREE_LETTER_OUTWARD_CODES[ substr( $postcode, 0, 3 ) ] ) ) {
			return str_pad( $postcode, 6, '0' );
		}

		if ( strlen( $postcode ) >= 2 && isset( self::TWO_LETTER_OUTWARD_CODES[ substr( $postcode, 0, 2 ) ] ) ) {
			return str_pad( $postcode, 5, '0' );
		}

		// let's assume the provided postcode has an outward code that we don't have in our registry, and pad it until it has length 7 (7 is the maximum length for GB postcodes).
		return str_pad( $postcode, 7, '0' );
	}
