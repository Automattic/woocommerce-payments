/** Validate the fixture's local backend before any demo operation. */
function wcpay_agent_demo_validate_environment(): void {
	$redirect = wp_parse_url( (string) get_option( 'wcpaydev_redirect_to' ) );
	if ( 'development' !== wp_get_environment_type() || ! class_exists( 'WC_Payments' ) || ! WC_Payments::mode()->is_test() || ! WC_Payments::mode()->is_dev() || ! get_option( 'wcpaydev_redirect' ) || 'host.docker.internal' !== ( $redirect['host'] ?? '' ) || 8086 !== (int) ( $redirect['port'] ?? 0 ) ) {
		throw new RuntimeException( 'Demo fixtures require the local V1 development server on port 8086 and WooPayments test mode.' );
	}
}
add_action( 'wcpay_agent_purchase_validate_environment', 'wcpay_agent_demo_validate_environment' );
add_filter( 'wcpay_agent_purchase_payment_method', static function (): string {
	wcpay_agent_demo_validate_environment();
	return 'pm_card_visa';
} );

// Taxes are enabled only while WooCommerce calculates the fixture cart.
add_action( 'wcpay_agent_purchase_before_quote', static function (): void {
	wcpay_agent_demo_validate_environment();
	add_filter( 'pre_option_woocommerce_calc_taxes', 'wcpay_agent_demo_enable_taxes' );
} );
add_action( 'wcpay_agent_purchase_after_quote', static function (): void {
	remove_filter( 'pre_option_woocommerce_calc_taxes', 'wcpay_agent_demo_enable_taxes' );
} );
/** Enable tax calculation for the demo fixture. */
function wcpay_agent_demo_enable_taxes(): string {
	return 'yes';
}

add_action( 'wcpay_agent_purchase_before_payment', static function (): void {
	wcpay_agent_demo_validate_environment();
	add_filter( 'pre_wp_mail', 'wcpay_agent_demo_suppress_mail' );
} );
add_action( 'wcpay_agent_purchase_after_payment', static function (): void {
	remove_filter( 'pre_wp_mail', 'wcpay_agent_demo_suppress_mail' );
} );
/** Suppress fixture payment emails. */
function wcpay_agent_demo_suppress_mail(): bool {
	return true;
}

/** Preserve the published local Docker port in links generated by WordPress. */
function wcpay_agent_demo_local_url( string $url ): string {
	if ( 'development' !== wp_get_environment_type() ) {
		return $url;
	}
	$parts = wp_parse_url( $url );
	if ( ! in_array( $parts['host'] ?? '', array( 'localhost', '127.0.0.1' ), true ) || ! empty( $parts['port'] ) ) {
		return $url;
	}
	return 'http://localhost:8082' . ( $parts['path'] ?? '' ) . ( isset( $parts['query'] ) ? '?' . $parts['query'] : '' ) . ( isset( $parts['fragment'] ) ? '#' . $parts['fragment'] : '' );
}
add_filter( 'home_url', 'wcpay_agent_demo_local_url' );
add_filter( 'site_url', 'wcpay_agent_demo_local_url' );
add_filter( 'plugins_url', 'wcpay_agent_demo_local_url' );
